//! Parsing helpers shared by the `JCODE_*` environment overrides.

/// A boolean from the usual spellings (`1/0`, `true/false`, `yes/no`, `on/off`).
pub fn parse_bool(raw: &str) -> Option<bool> {
    match raw.trim().to_lowercase().as_str() {
        "1" | "true" | "yes" | "on" => Some(true),
        "0" | "false" | "no" | "off" => Some(false),
        _ => None,
    }
}

/// A comma or newline separated list with blanks dropped.
pub fn parse_list(raw: &str) -> Vec<String> {
    raw.split([',', '\n'])
        .map(str::trim)
        .filter(|part| !part.is_empty())
        .map(ToString::to_string)
        .collect()
}
