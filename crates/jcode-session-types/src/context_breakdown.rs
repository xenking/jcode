use serde::{Deserialize, Serialize};

pub const CONTEXT_BREAKDOWN_CAPABILITY: &str = "session_context_breakdown";

/// Counts only. No prompt fragments, tool names, paths or message contents.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ContextBreakdown {
    pub session_id: Option<String>,
    pub model: Option<String>,
    /// Legacy mirror of `meter.occupied_tokens`.
    pub total_tokens: Option<u64>,
    /// Legacy context budget, not an auto-compaction trigger.
    pub limit_tokens: Option<u64>,
    /// Category counts are estimates, even when the total has a usage anchor.
    pub estimated: bool,
    pub categories: Vec<ContextBreakdownCategory>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub meter: Option<ContextMeter>,
    /// Occupancy minus the sum of known estimated components. This is not a
    /// category or an estimate of how much unknown content exists.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub residual_tokens: Option<i64>,
    /// Read-only plans from the same live snapshot as the breakdown.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub action_forecast: Option<ContextActionForecast>,
}

#[derive(Debug, Default, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ContextMeter {
    pub state: ContextMeterState,
    pub occupied_tokens: Option<u64>,
    pub source: ContextOccupancySource,
    pub measured_at_ms: Option<i64>,
    /// Serving route snapshot. An unverified historical report has no route.
    pub route: Option<String>,
    pub model_window_tokens: Option<u64>,
    pub effective_budget_tokens: Option<u64>,
    pub session_cap_tokens: Option<u64>,
    pub compaction_mode: Option<String>,
    /// Automatic trigger, not a context budget. In `saved` state this is the
    /// recorded policy, not a recomputation against current daemon settings.
    pub compaction_threshold_tokens: Option<u64>,
    pub idle_precompaction_tokens: Option<u64>,
    /// Published pricing boundary for one request's total input, never occupancy.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub long_context_pricing_above_input_tokens: Option<u64>,
}

#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ContextMeterState {
    Live,
    Saved,
    Draft,
    #[default]
    Unavailable,
}

#[derive(Debug, Default, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ContextOccupancySource {
    ProviderReported,
    HistoricalReport,
    CompactionEstimate,
    LocalEstimate,
    #[default]
    Unknown,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ContextActionForecast {
    /// Locally estimated current context, never the model limit or past usage.
    pub current_tokens: Option<u64>,
    pub compact: Option<ContextActionSavings>,
    pub shake: Option<ContextActionSavings>,
    /// Dry-run of the local Snapcompact artifact. Does not include any
    /// optional decisions generated by a provider.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub compact_measurement: Option<ContextActionMeasurement>,
    // Keep new statuses separate so old clients can still read the breakdown.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub compact_status: Option<ContextActionStatus>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub shake_status: Option<ContextActionStatus>,
}

impl ContextActionForecast {
    pub fn unavailable(status: ContextActionStatus) -> Self {
        Self {
            current_tokens: None,
            compact: None,
            shake: None,
            compact_measurement: None,
            compact_status: Some(status),
            shake_status: Some(status),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ContextActionStatus {
    NoEligible,
    Unsupported,
    Busy,
    /// The planner can start, but the resulting artifact size is unknown.
    SavingsUnknown,
    /// No live planner was available to inspect.
    Unknown,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ContextActionSavings {
    NoChange,
    Estimate { tokens: u64 },
    UpperBound { tokens: u64 },
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ContextActionMeasurement {
    pub before_tokens: u64,
    pub after_tokens: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ContextBreakdownCategory {
    pub kind: ContextBreakdownKind,
    /// None means the data is unavailable, not that the category is empty.
    pub tokens: Option<u64>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ContextBreakdownKind {
    SystemPrompt,
    BuiltinTools,
    SkillsModes,
    DynamicTools,
    Agents,
    Conversation,
    /// The outbound snapcompact checkpoint, excluding unused archive contents.
    Snapcompact,
    /// Estimated input whose category is not known. Not a usage discrepancy.
    Unattributed,
}
